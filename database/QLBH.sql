IF DB_ID(N'QLBH') IS NULL CREATE DATABASE QLBH;
GO
USE QLBH;
GO
IF OBJECT_ID(N'dbo.CTHoaDon', N'U') IS NOT NULL DROP TABLE dbo.CTHoaDon;
IF OBJECT_ID(N'dbo.HoaDon', N'U') IS NOT NULL DROP TABLE dbo.HoaDon;
IF OBJECT_ID(N'dbo.HangHoa', N'U') IS NOT NULL DROP TABLE dbo.HangHoa;
GO
CREATE TABLE dbo.HangHoa (
    MaHH INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TenHH NVARCHAR(100) NOT NULL,
    DonViTinh NVARCHAR(50) NULL,
    DonGia FLOAT NOT NULL CHECK (DonGia >= 0)
);
CREATE TABLE dbo.HoaDon (
    MaHD INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    NgayLapHD DATETIME NOT NULL,
    KhachHang NVARCHAR(100) NOT NULL,
    TongTien FLOAT NOT NULL CHECK (TongTien >= 0)
);
CREATE TABLE dbo.CTHoaDon (
    MaHD INT NOT NULL,
    MaHH INT NOT NULL,
    SoLuong INT NOT NULL CHECK (SoLuong > 0),
    CONSTRAINT PK_CTHoaDon PRIMARY KEY (MaHD, MaHH),
    CONSTRAINT FK_CTHoaDon_HoaDon FOREIGN KEY (MaHD) REFERENCES dbo.HoaDon(MaHD),
    CONSTRAINT FK_CTHoaDon_HangHoa FOREIGN KEY (MaHH) REFERENCES dbo.HangHoa(MaHH)
);
GO
